class SeedSafetyError(Exception):
    """Raised when it is not safe to proceed with seeding."""


def _check_database_safety(database_url: str, *, allow_dev: bool) -> str:
    """
    Refuse to proceed unless it's safe to seed the resolved database.
    Returns the (non-secret) database name on success. Raises
    `SeedSafetyError` otherwise -- callers must not open a DB session if
    this raises.
    """
    db_name = make_url(database_url).database or "<unknown>"

    if "test" in db_name.lower():
        raise SeedSafetyError(
            f"Refusing to seed database '{db_name}': its name contains "
            "'test', which looks like this project's isolated test "
            "database (e.g. 'karmanya_test'). This script must never run "
            "against a test database."
        )

    if not allow_dev:
        raise SeedSafetyError(
            f"About to seed database '{db_name}'. Re-run with "
            "--yes-seed-development to confirm this is intentional."
        )

    return db_name


