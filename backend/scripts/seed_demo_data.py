"""
Phase 5F — deterministic, idempotent demo/base data for the Karmanya
backend.

Seeds BASE ENTITIES ONLY: one Federation, two Associations, the nine
Service rows both associations' workers need, four org-level Accounts
(Federation Admin, the two Association Admins, the demo User + its
UserProfile), and 215 Worker Accounts + Worker rows + WorkerSkill rows.
It deliberately does NOT seed ServiceRequest, Assignment, LeaveRequest,
Payment, Review, Notification, or any other lifecycle/booking data — that
is out of scope for this phase.

--------------------------------------------------------------------------
Admin dataset as source of truth
--------------------------------------------------------------------------
The 215 demo workers are NOT a second, independently authored dataset.
`admin/src/data/workerCatalog.ts` already generates the canonical 215
workers (120 "SKW-####" + 95 "GEN-####") from a small seeded PRNG
(`mulberry32`, seeds 20260914/20260915) — see that file for the original
TypeScript. `_generate_demo_workers()` below is a faithful, standalone
Python re-implementation of that exact algorithm (same constant pools,
same per-worker call order, same PRNG), so the two datasets are
guaranteed to agree without this backend ever importing or running any
TypeScript at seed time. This was verified this phase by running both
implementations side by side and diffing all 215 generated records
field-for-field (workerId, fullName, phoneNumber, address, pincode,
skills, rating, totalJobsCompleted, workerStatus) — zero mismatches.

Only identity/profile/skill fields are reproduced. `currentWorkload`,
`availabilityStatus`, `upcomingLeave`, and `currentAssignments` are
deliberately out of Phase 5F's locked scope and are never persisted here
-- but the PRNG calls those fields would have consumed in the original
generator ARE still replicated internally (see the comment inside
`_generate_workers_for_association`), because `workerStatus` (which we DO
need) is generated by the very last random() call for each worker, after
the calls those discarded fields would have made. Skipping those calls
would desynchronize the PRNG stream from `workerCatalog.ts` and silently
corrupt every worker generated after the first skipped one.

--------------------------------------------------------------------------
Admin skill -> backend Service mapping
--------------------------------------------------------------------------
The Admin generator's skill vocabulary (noun-form trade names) is mapped
onto this Phase 5F's locked, backend `Service.name` catalogue (see
`_SKILL_TO_SERVICE_NAME` below). `Service` is a global table (no
`association_id` column — see `app/models/service.py`); the same
`Service` row (e.g. "Plumbing") is intentionally shared by both
associations' workers via separate `WorkerSkill` rows, rather than being
duplicated per association.

--------------------------------------------------------------------------
Mukesh Yadav override
--------------------------------------------------------------------------
Worker `SKW-0066` is generated by the algorithm above as "Mukesh Yadav"
in the Skilled association with pincode 826004 -- already correct without
any change. Its `address`, `rating`, and `total_jobs_completed` do NOT
match the locked Phase 5F demo values on their own, so
`_MUKESH_OVERRIDE` explicitly overwrites exactly those three fields after
generation, before the row is written to the backend. This never touches
`admin/src/data/workerCatalog.ts` itself -- the override is applied only
to the backend's own copy of the data. `full_name` is intentionally not
part of the override (see "Worker full name / phone number" below);
`SKW-0066`'s `worker_code` is the only identity this script ever uses to
recognize the row, since a second worker ("SKW-0080") is independently
generated with the same name.

--------------------------------------------------------------------------
Worker full name / phone number
--------------------------------------------------------------------------
`Worker.full_name` (`String(255)`, **NOT NULL**) and `Worker.phone`
(`String(32)`, nullable) are existing columns on the current Worker
schema. `Worker.full_name` is populated from the Admin generator's
`fullName` (e.g. "Mukesh Yadav" for `SKW-0066`) and `Worker.phone` from
its `phoneNumber`, for every seeded worker -- `full_name` is required
simply because it is a `NOT NULL` column on the existing schema, not an
optional enhancement this script chose to add. No model change and no
migration were needed or made; both columns already existed before this
script was written.

--------------------------------------------------------------------------
Demo worker password convention (DEMO-ONLY)
--------------------------------------------------------------------------
Every seeded Worker Account's `login_id` is simply its `worker_code`
(e.g. "SKW-0066"), already guaranteed globally unique by the generator.
Its plaintext demo password is deterministically derived as
`f"{worker_code.lower().replace('-', '')}123"` (e.g. "skw0066123"),
mirroring the existing demo-account convention already used by
`admin/src/data/demoAccounts.ts` ("skilled123", "general123", "user123").
This is NOT a real authentication scheme -- it exists purely so a demo
worker login can be typed by hand -- and is always passed through
`app.auth.security.hash_password()` before storage; the plaintext value
is never persisted.

--------------------------------------------------------------------------
Fixed organization UUIDs
--------------------------------------------------------------------------
`Federation.name` and `Association.name` are NOT unique columns (confirmed
by reading both models), so a rerun of this script cannot safely
rediscover "the" demo Federation/Association by name alone -- a
coincidentally-same-named row created by someone else would be
indistinguishable from this script's own row. Instead, the three
singleton demo organization rows are looked up (and, on first run,
created) by a FIXED, deterministic UUID -- generated once via
`uuid.uuid5()` against a fixed local namespace + a stable label, so the
values are reproducible from this source file alone rather than being
inscrutable hardcoded literals. Explicitly supplying `id=` at
construction time is fully compatible with `Federation`/`Association` as
defined (`default=uuid.uuid4` is a Python-side default that only applies
when no value is supplied); no model/column change is needed or made.
If a row already exists at that fixed id but its name or federation
relationship doesn't match what this script expects, the script fails
loudly (`SeedIntegrityError`) rather than silently overwriting or
repurposing an unexpected row.

--------------------------------------------------------------------------
Development-database safety guard
--------------------------------------------------------------------------
See `_check_database_safety()`. Resolves `DATABASE_URL` via the existing
`app.config.get_settings()` (no hardcoded credentials anywhere), refuses
outright if the resolved database name contains "test" (this suite's
existing test databases are always named e.g. `karmanya_test`), and
otherwise requires an explicit `--yes-seed-development` CLI flag before
touching the resolved (real) database. No DB session is ever opened if
either check fails.

--------------------------------------------------------------------------
Usage
--------------------------------------------------------------------------
    python scripts/seed_demo_data.py --yes-seed-development

Idempotent: rerunning creates nothing new for entities that already
exist (recognized by their id/login_id/worker_code/name/composite key as
documented above) and reconciles their canonical demo field values,
without touching any row this script doesn't recognize as one of its
own.
"""

