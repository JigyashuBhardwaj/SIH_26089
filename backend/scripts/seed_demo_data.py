@dataclass(frozen=True)
class GeneratedWorker:
    """Identity/profile/skill fields for one demo worker, exactly as the
    Admin generator would produce them (before any Phase 5F override)."""

    worker_code: str
    association_slug: str
    full_name: str
    phone_number: str
    address: str
    pincode: str
    skills: tuple[str, ...]
    rating: float
    total_jobs_completed: int
    worker_status: str  # "Active" | "Inactive"


def _generate_workers_for_association(cfg: _AssociationSeedConfig) -> list[GeneratedWorker]:
    random = _create_seeded_random(cfg.seed)
    workers: list[GeneratedWorker] = []

    for i in range(cfg.count):
        worker_number = i + 1
        worker_code = f"{cfg.id_prefix}-{worker_number:04d}"

        full_name = f"{_pick(random, _FIRST_NAMES)} {_pick(random, _LAST_NAMES)}"

        primary_skill = cfg.skill_pool[i % len(cfg.skill_pool)]
        skills: list[str] = [primary_skill]
        extra_skill_count = _int_between(random, 0, 2)
        for _ in range(extra_skill_count):
            # Mirrors the original's `Set.add()`: consumes one random()
            # call per iteration regardless of whether the picked skill
            # was already present.
            candidate = _pick(random, cfg.skill_pool)
            if candidate not in skills:
                skills.append(candidate)

        house_number = _int_between(random, 1, 400)
        colony = _pick(random, _COLONY_NAMES)
        pincode = _pick(random, _PINCODES)
        address = f"House No. {house_number}, {colony}, Dhanbad, Jharkhand"

        association_block = 0 if cfg.id_prefix == "SKW" else 20000
        phone_number = f"+91-90000-{str(association_block + 10000 + worker_number)[-5:]}"

        rating = _js_round((4.0 + random() * 1.0) * 10) / 10
        total_jobs_completed = _int_between(random, 5, 260)

        # --- Everything below this point is OUT OF PHASE 5F SCOPE and is
        # never persisted -- but the calls themselves are kept exactly as
        # the original makes them, because `worker_status` (which we DO
        # need) is generated by the very last random() call for this
        # worker, after all of these. Skipping any of these calls would
        # desynchronize every subsequent worker's generated identity from
        # admin/src/data/workerCatalog.ts.
        availability_roll = random()
        if availability_roll < 0.6:
            availability_status = "Available"
        elif availability_roll < 0.85:
            availability_status = "Busy"
        else:
            availability_status = "Unavailable"

        leave_roll = random()
        if leave_roll < 0.12:
            _int_between(random, -3, 0)
            _int_between(random, 2, 6)
        elif leave_roll < 0.2:
            _int_between(random, 7, 30)
            _int_between(random, 2, 5)

        if availability_status == "Busy":
            current_workload = _int_between(random, 2, 6)
        elif availability_status == "Available":
            current_workload = _int_between(random, 0, 1)
        else:
            current_workload = 0

        for _ in range(current_workload):
            _pick(random, skills)
            _int_between(random, 0, 6)
            _pick(random, _ASSIGNMENT_TIME_SLOTS)
            _pick(random, _ASSIGNMENT_STATUSES)
        # --- end out-of-scope PRNG-synchronization block.

        worker_status = "Inactive" if random() < 0.05 else "Active"

        workers.append(
            GeneratedWorker(
                worker_code=worker_code,
                association_slug=cfg.slug,
                full_name=full_name,
                phone_number=phone_number,
                address=address,
                pincode=pincode,
                skills=tuple(skills),
                rating=rating,
                total_jobs_completed=total_jobs_completed,
                worker_status=worker_status,
            )
        )

    return workers


def _apply_mukesh_override(workers: list[GeneratedWorker]) -> list[GeneratedWorker]:
    """Overwrite exactly address/pincode/rating/total_jobs_completed for
    worker_code == SKW-0066, leaving every other worker (including the
    second "Mukesh Yadav" at SKW-0080) untouched."""
    result = []
    for worker in workers:
        if worker.worker_code == _MUKESH_WORKER_CODE:
            worker = GeneratedWorker(
                worker_code=worker.worker_code,
                association_slug=worker.association_slug,
                full_name=worker.full_name,
                phone_number=worker.phone_number,
                address=_MUKESH_OVERRIDE["address"],
                pincode=_MUKESH_OVERRIDE["pincode"],
                skills=worker.skills,
                rating=float(_MUKESH_OVERRIDE["rating"]),
                total_jobs_completed=_MUKESH_OVERRIDE["total_jobs_completed"],
                worker_status=worker.worker_status,
            )
        result.append(worker)
    return result


def generate_demo_workers() -> list[GeneratedWorker]:
    """The full, deterministic 215-worker dataset (120 Skilled + 95
    General), with the Mukesh Yadav override applied."""
    workers: list[GeneratedWorker] = []
    for cfg in _ASSOCIATION_SEEDS:
        workers.extend(_generate_workers_for_association(cfg))
    return _apply_mukesh_override(workers)


