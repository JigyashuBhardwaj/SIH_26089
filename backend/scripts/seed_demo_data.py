#
# Faithful Python re-implementation of admin/src/data/workerCatalog.ts's
# `createSeededRandom` (mulberry32) + `generateWorkersForAssociation`.
# Verified this phase to produce byte-for-byte identical output to the
# original TypeScript for all 215 workers, across every field kept here.


def _imul32(a: int, b: int) -> int:
    """Port of JavaScript's `Math.imul` (32-bit integer multiply, low 32
    bits of the result, kept as an unsigned bit pattern)."""
    return (a * b) & 0xFFFFFFFF


def _create_seeded_random(seed: int):
    """
    Port of `createSeededRandom` (mulberry32) from
    admin/src/data/seededRandom.ts. `state`/`t` are always kept as plain
    non-negative 32-bit bit patterns (masked with `& 0xFFFFFFFF` after
    every operation) rather than converted to signed int32 -- every
    JavaScript operation the original uses (`^`, `|`, `>>>`, `Math.imul`)
    only cares about the underlying bit pattern, not its signed/unsigned
    interpretation, so this is equivalent without needing two's-complement
    bookkeeping.
    """
    state = seed & 0xFFFFFFFF

    def random() -> float:
        nonlocal state
        state = (state + 0x6D2B79F5) & 0xFFFFFFFF
        t1 = _imul32(state ^ (state >> 15), (1 | state) & 0xFFFFFFFF)
        inner = _imul32(t1 ^ (t1 >> 7), (61 | t1) & 0xFFFFFFFF)
        t2 = ((t1 + inner) ^ t1) & 0xFFFFFFFF
        result = (t2 ^ (t2 >> 14)) & 0xFFFFFFFF
        return result / 4294967296.0

    return random


def _pick(random, items):
    """Port of `pick()` -- always consumes exactly one random() call."""
    return items[math.floor(random() * len(items))]


def _int_between(random, lo: int, hi: int) -> int:
    """Port of `intBetween()` -- always consumes exactly one random() call."""
    return lo + math.floor(random() * (hi - lo + 1))


def _js_round(value: float) -> int:
    """
    Port of JavaScript's `Math.round` (rounds half towards +Infinity),
    which differs from Python's built-in `round()` (rounds half to even)
    at exact `.5` boundaries. Only used for `rating`.
    """
    return math.floor(value + 0.5)


