class SeedValidationError(Exception):
    """Raised with every failed validation check joined together."""


def validate_seed(session: Session, generated_workers: list[GeneratedWorker]) -> None:
    """
    Ownership-based validation: confirms every canonical demo entity this
    script owns exists with the expected values. Deliberately does NOT
    assert anything about the database's TOTAL row counts (e.g. "exactly
    215 Worker rows exist") -- the development database may legitimately
    contain other, non-demo workers/accounts/services alongside these,
    and validation must not fail just because it does. Every check below
    looks up a specific, known canonical row (by worker_code/login_id/
    service name/fixed UUID) and checks its values; it never scans "all
    rows of table X" and compares the count to an expected total.
    """
    problems: list[str] = []

    federation = session.get(Federation, FEDERATION_ID)
    if federation is None or federation.name != FEDERATION_NAME:
        problems.append("Federation row missing or incorrect.")

    assoc_skilled = session.get(Association, ASSOCIATION_SKILLED_ID)
    if assoc_skilled is None or assoc_skilled.name != ASSOCIATION_SKILLED_NAME:
        problems.append("Skilled Association row missing or incorrect.")
    assoc_general = session.get(Association, ASSOCIATION_GENERAL_ID)
    if assoc_general is None or assoc_general.name != ASSOCIATION_GENERAL_NAME:
        problems.append("General Association row missing or incorrect.")

    # Only checks that these nine specific, named Service rows exist and
    # are active -- never asserts that the `services` table contains only
    # these nine.
    services = {
        s.name: s
        for s in session.execute(
            select(Service).where(Service.name.in_(SERVICE_CATALOGUE))
        ).scalars()
    }
    missing_services = set(SERVICE_CATALOGUE) - set(services)
    if missing_services:
        problems.append(f"Missing Service rows: {sorted(missing_services)}")
    for name, service in services.items():
        if not service.is_active:
            problems.append(f"Service {name!r} is not active.")

    for login_id, expected_role in (
        ("federation_admin", AccountRole.FEDERATION_ADMIN),
        ("dhanbad_skilled", AccountRole.ASSOCIATION_ADMIN),
        ("dhanbad_general", AccountRole.ASSOCIATION_ADMIN),
        ("demo_user", AccountRole.USER),
    ):
        account = session.execute(select(Account).where(Account.login_id == login_id)).scalar_one_or_none()
        if account is None or account.role != expected_role:
            problems.append(f"Account {login_id!r} missing or has wrong role.")

    # Canonical worker_codes only -- looked up by name, not "every Worker
    # row in the table". A Worker row this script doesn't recognize is
    # simply never touched by any of this.
    expected_codes = [w.worker_code for w in generated_workers]
    canonical_workers = {
        w.worker_code: w
        for w in session.execute(
            select(Worker).where(Worker.worker_code.in_(expected_codes))
        ).scalars()
    }
    missing_codes = set(expected_codes) - set(canonical_workers)
    if missing_codes:
        problems.append(f"{len(missing_codes)} canonical worker(s) missing, e.g. {sorted(missing_codes)[:5]}.")

    skilled_count = sum(
        1 for w in canonical_workers.values() if w.association_id == ASSOCIATION_SKILLED_ID
    )
    general_count = sum(
        1 for w in canonical_workers.values() if w.association_id == ASSOCIATION_GENERAL_ID
    )
    if skilled_count != 120:
        problems.append(f"Expected 120 canonical Skilled workers, found {skilled_count}.")
    if general_count != 95:
        problems.append(f"Expected 95 canonical General workers, found {general_count}.")

    # Canonical worker accounts (by login_id == worker_code) -- again,
    # never "every Account with role WORKER in the table".
    canonical_worker_accounts = {
        a.login_id: a
        for a in session.execute(
            select(Account).where(Account.login_id.in_(expected_codes))
        ).scalars()
    }

    association_id_by_slug = {
        "dhanbad_skilled": ASSOCIATION_SKILLED_ID,
        "dhanbad_general": ASSOCIATION_GENERAL_ID,
    }
    skill_rows_by_worker_id: dict[uuid.UUID, set[uuid.UUID]] = {}
    if canonical_workers:
        for row in session.execute(
            select(WorkerSkill).where(
                WorkerSkill.worker_id.in_([w.id for w in canonical_workers.values()])
            )
        ).scalars():
            skill_rows_by_worker_id.setdefault(row.worker_id, set()).add(row.service_id)

    service_ids_by_name = {name: svc.id for name, svc in services.items()}
    services_used_by_canonical_workers: set[uuid.UUID] = set()

    for generated in generated_workers:
        worker = canonical_workers.get(generated.worker_code)
        if worker is None:
            continue  # already reported as missing above

        expected_association_id = association_id_by_slug[generated.association_slug]
        if worker.association_id != expected_association_id:
            problems.append(f"Worker {generated.worker_code} is not in the expected association.")
        if not worker.full_name:
            problems.append(f"Worker {generated.worker_code} has an empty full_name.")
        elif worker.full_name != generated.full_name:
            problems.append(f"Worker {generated.worker_code} full_name does not match the generator.")
        if worker.phone != generated.phone_number:
            problems.append(f"Worker {generated.worker_code} phone does not match the generator.")
        # NOTE: `generated` here is an element of `generated_workers`,
        # which already has `_apply_mukesh_override()` applied (see
        # `generate_demo_workers()`) -- so for SKW-0066, `generated.address`
        # /`.pincode`/`.rating`/`.total_jobs_completed` already ARE the
        # override values, and comparing against `generated.*` directly
        # (rather than branching on worker_code again here) checks the
        # override for free, for every worker in one pass.
        if worker.address != generated.address:
            problems.append(f"Worker {generated.worker_code} address does not match the expected value.")
        if worker.pincode != generated.pincode:
            problems.append(f"Worker {generated.worker_code} pincode does not match the expected value.")
        if worker.rating != Decimal(str(generated.rating)):
            problems.append(f"Worker {generated.worker_code} rating does not match the expected value.")
        if worker.total_jobs_completed != generated.total_jobs_completed:
            problems.append(f"Worker {generated.worker_code} total_jobs_completed does not match the expected value.")
        expected_status = WorkerStatus.INACTIVE if generated.worker_status == "Inactive" else WorkerStatus.ACTIVE
        if worker.status != expected_status:
            problems.append(f"Worker {generated.worker_code} status does not match the generator.")

        account = canonical_worker_accounts.get(generated.worker_code)
        if account is None or account.role != AccountRole.WORKER:
            problems.append(f"Worker {generated.worker_code} has no valid WORKER account.")
        else:
            if account.association_id != worker.association_id:
                problems.append(f"Worker {generated.worker_code} account/worker association mismatch.")
            if account.federation_id is not None:
                problems.append(f"Worker {generated.worker_code} account has a non-null federation_id.")

        expected_service_ids = set()
        for admin_skill in generated.skills:
            service_name = _SKILL_TO_SERVICE_NAME[admin_skill]
            service_id = service_ids_by_name.get(service_name)
            if service_id is None:
                problems.append(f"Service {service_name!r} (needed by {generated.worker_code}) is missing.")
                continue
            expected_service_ids.add(service_id)
        actual_service_ids = skill_rows_by_worker_id.get(worker.id, set())
        missing_skills = expected_service_ids - actual_service_ids
        if missing_skills:
            problems.append(f"Worker {generated.worker_code} is missing {len(missing_skills)} expected WorkerSkill row(s).")
        services_used_by_canonical_workers |= actual_service_ids & expected_service_ids

    # Every canonical service must be used by at least one canonical
    # worker -- computed only from the canonical workers/skills gathered
    # above, never from "every WorkerSkill row in the table".
    for name, service_id in service_ids_by_name.items():
        if service_id not in services_used_by_canonical_workers:
            problems.append(f"Service {name!r} has zero canonical workers.")

    # Mukesh Yadav override -- exact values, by worker_code only.
    mukesh_generated = next((w for w in generated_workers if w.worker_code == _MUKESH_WORKER_CODE), None)
    if mukesh_generated is None or mukesh_generated.full_name != "Mukesh Yadav":
        problems.append("Generated SKW-0066 identity is not 'Mukesh Yadav' -- generator port drifted.")
    mukesh_worker = canonical_workers.get(_MUKESH_WORKER_CODE)
    if mukesh_worker is None:
        problems.append("SKW-0066 Worker row missing.")
    else:
        if mukesh_worker.association_id != ASSOCIATION_SKILLED_ID:
            problems.append("SKW-0066 is not in the Skilled association.")
        if mukesh_worker.full_name != "Mukesh Yadav":
            problems.append(f"SKW-0066 full_name is {mukesh_worker.full_name!r}, expected 'Mukesh Yadav'.")
        if mukesh_generated is not None and mukesh_worker.phone != mukesh_generated.phone_number:
            problems.append("SKW-0066 phone does not match the generator's phoneNumber.")
        if mukesh_worker.address != _MUKESH_OVERRIDE["address"]:
            problems.append("SKW-0066 address override not applied.")
        if mukesh_worker.pincode != _MUKESH_OVERRIDE["pincode"]:
            problems.append("SKW-0066 pincode override not applied.")
        if mukesh_worker.rating != _MUKESH_OVERRIDE["rating"]:
            problems.append(f"SKW-0066 rating is {mukesh_worker.rating}, expected 4.80.")
        if mukesh_worker.total_jobs_completed != _MUKESH_OVERRIDE["total_jobs_completed"]:
            problems.append("SKW-0066 total_jobs_completed override not applied.")

    federation_admin = session.execute(
        select(Account).where(Account.login_id == "federation_admin")
    ).scalar_one_or_none()
    if federation_admin is None or not verify_password("federation123", federation_admin.password_hash or ""):
        problems.append("federation_admin password hash does not verify.")
    demo_user = session.execute(select(Account).where(Account.login_id == "demo_user")).scalar_one_or_none()
    if demo_user is None or not verify_password("user123", demo_user.password_hash or ""):
        problems.append("demo_user password hash does not verify.")
    mukesh_account = canonical_worker_accounts.get("SKW-0066")
    if mukesh_account is None or not verify_password("skw0066123", mukesh_account.password_hash or ""):
        problems.append("SKW-0066 worker account password hash does not verify.")

    if problems:
        raise SeedValidationError("; ".join(problems))


