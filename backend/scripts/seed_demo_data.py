@dataclass
class SeedResult:
    federation_id: uuid.UUID
    association_skilled_id: uuid.UUID
    association_general_id: uuid.UUID
    service_count: int
    worker_count: int

    def summary(self) -> str:
        return (
            "Phase 5F demo data seeded successfully: "
            f"1 federation, 2 associations, {self.service_count} services, "
            f"{self.worker_count} workers (+ matching accounts/skills)."
        )


def run_seed(session: Session) -> SeedResult:
    """
    Seed (or reconcile) every Phase 5F demo entity into `session`, and
    validate the result. Does NOT commit or rollback -- that is the
    caller's responsibility (see `main()`), which is what makes this
    function directly reusable from tests against an injected session.
    """
    federation = _get_or_create_federation(session)
    assoc_skilled = _get_or_create_association(
        session,
        association_id=ASSOCIATION_SKILLED_ID,
        name=ASSOCIATION_SKILLED_NAME,
        federation_id=federation.id,
    )
    assoc_general = _get_or_create_association(
        session,
        association_id=ASSOCIATION_GENERAL_ID,
        name=ASSOCIATION_GENERAL_NAME,
        federation_id=federation.id,
    )
    association_id_by_slug = {
        "dhanbad_skilled": assoc_skilled.id,
        "dhanbad_general": assoc_general.id,
    }

    service_ids: dict[str, uuid.UUID] = {}
    for name in SERVICE_CATALOGUE:
        service = _get_or_create_service(session, name)
        session.flush()  # need service.id for WorkerSkill rows below
        service_ids[name] = service.id

    _get_or_create_org_account(
        session,
        login_id="federation_admin",
        password="federation123",
        role=AccountRole.FEDERATION_ADMIN,
        association_id=None,
        federation_id=federation.id,
    )
    _get_or_create_org_account(
        session,
        login_id="dhanbad_skilled",
        password="skilled123",
        role=AccountRole.ASSOCIATION_ADMIN,
        association_id=assoc_skilled.id,
        federation_id=None,
    )
    _get_or_create_org_account(
        session,
        login_id="dhanbad_general",
        password="general123",
        role=AccountRole.ASSOCIATION_ADMIN,
        association_id=assoc_general.id,
        federation_id=None,
    )
    demo_user_account = _get_or_create_org_account(
        session,
        login_id="demo_user",
        password="user123",
        role=AccountRole.USER,
        association_id=None,
        federation_id=None,
    )
    session.flush()  # need demo_user_account.id for its UserProfile
    _get_or_create_user_profile(session, demo_user_account, full_name="Madhav")

    generated_workers = generate_demo_workers()
    for generated in generated_workers:
        association_id = association_id_by_slug[generated.association_slug]
        account = _get_or_create_worker_account(session, generated, association_id)
        session.flush()  # need account.id for the Worker row
        worker = _get_or_create_worker(session, account=account, association_id=association_id, generated=generated)
        session.flush()  # need worker.id for its WorkerSkill rows
        for admin_skill in generated.skills:
            service_name = _SKILL_TO_SERVICE_NAME[admin_skill]
            _ensure_worker_skill(session, worker_id=worker.id, service_id=service_ids[service_name])

    session.flush()
    validate_seed(session, generated_workers)

    return SeedResult(
        federation_id=federation.id,
        association_skilled_id=assoc_skilled.id,
        association_general_id=assoc_general.id,
        service_count=len(service_ids),
        worker_count=len(generated_workers),
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--yes-seed-development",
        action="store_true",
        help="Confirm seeding the resolved (non-test) DATABASE_URL.",
    )
    args = parser.parse_args(argv)

    settings = get_settings()
    try:
        db_name = _check_database_safety(settings.database_url, allow_dev=args.yes_seed_development)
    except SeedSafetyError as exc:
        print(f"Refusing to seed: {exc}", file=sys.stderr)
        return 1

    print(f"Seeding Phase 5F demo data into database '{db_name}'...")
    session = SessionLocal()
    try:
        result = run_seed(session)
        session.commit()
    except Exception as exc:  # noqa: BLE001 - intentionally broad: any failure must roll back
        session.rollback()
        print(f"Seeding failed, rolled back: {exc}", file=sys.stderr)
        return 1
    finally:
        session.close()

    print(result.summary())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
